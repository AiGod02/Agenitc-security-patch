/**
 * Captures REAL Jest --json outputs for Slice S3 unit tests (Section 1.1 & Section 12A).
 * Run from repo root: node tests/data/capture/capture_jest_cases.js
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const childProcess = require("child_process");

const ROOT = path.resolve(__dirname, "../../..");
const FIXTURE_MODULES = path.join(ROOT, "fixture/express-fixture/node_modules");
const JEST_BIN = path.join(FIXTURE_MODULES, "jest/bin/jest.js");
const OUT_DIR = path.resolve(__dirname, "..");

const CASES = [
  {
    name: "tagged_failure",
    extraArgs: [],
    code: `
const { invariant } = require("./invariant");
test("reproduces IDOR invariant failure", () => {
  invariant("IDOR-INVOICE-READ", false, "Bob received HTTP 200 for Alice invoice");
});
`,
  },
  {
    name: "passing_test",
    extraArgs: [],
    code: `
const { invariant } = require("./invariant");
test("invariant holds on clean route", () => {
  invariant("IDOR-INVOICE-READ", true, "Access denied properly");
});
`,
  },
  {
    name: "missing_module",
    extraArgs: [],
    code: `
const nonExistent = require("./does-not-exist-anywhere");
test("never reached", () => {
  expect(nonExistent).toBeDefined();
});
`,
  },
  {
    name: "jest_timeout",
    extraArgs: ["--testTimeout=120"],
    code: `
test("hangs past jest timeout", async () => {
  await new Promise((resolve) => setTimeout(resolve, 600));
});
`,
  },
  {
    name: "port_in_use",
    extraArgs: [],
    code: `
const net = require("net");
test("triggers real EADDRINUSE", async () => {
  const s1 = net.createServer();
  const s2 = net.createServer();
  await new Promise((resolve, reject) => s1.listen(0, "127.0.0.1", (err) => err ? reject(err) : resolve()));
  const port = s1.address().port;
  try {
    await new Promise((resolve, reject) => {
      s2.once("error", reject);
      s2.listen(port, "127.0.0.1", resolve);
    });
  } finally {
    s1.close();
    try { s2.close(); } catch (_e) {}
  }
});
`,
  },
  {
    name: "wrong_tag",
    extraArgs: [],
    code: `
const { invariant } = require("./invariant");
test("fails with different invariant tag", () => {
  invariant("OTHER-INVARIANT-ID", false, "Different failure triggered");
});
`,
  },
  {
    name: "no_tag_failure",
    extraArgs: [],
    code: `
test("ordinary expect failure without invariant tag", () => {
  expect(200).toBe(403);
});
`,
  },
];

function main() {
  const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "psa-jest-capture-"));
  fs.writeFileSync(
    path.join(workDir, "package.json"),
    JSON.stringify({ name: "jest-capture", private: true, jest: { testEnvironment: "node" } }, null, 2)
  );
  fs.copyFileSync(
    path.join(ROOT, "fixture/express-fixture/tests/helpers/invariant.js"),
    path.join(workDir, "invariant.js")
  );

  const manifestLines = [
    "# Captured Real Jest JSON Outputs (`tests/data/`)",
    "",
    "Generated by running `node tests/data/capture/capture_jest_cases.js` against real Jest (`29.7.0`).",
    "",
    "| File | Command | Exit Code |",
    "|---|---|---|",
  ];

  for (const item of CASES) {
    const relTestName = `${item.name}.test.js`;
    const testFile = path.join(workDir, relTestName);
    fs.writeFileSync(testFile, item.code.trim() + "\n", "utf8");
    const args = [JEST_BIN, "--runInBand", "--json", "--runTestsByPath", ...item.extraArgs, relTestName];
    const res = childProcess.spawnSync(process.execPath, args, {
      cwd: workDir,
      env: { ...process.env, NODE_PATH: FIXTURE_MODULES },
      encoding: "utf8",
      timeout: 30000,
    });
    if (!res.stdout || !res.stdout.trim()) {
      throw new Error(`Jest produced empty stdout for ${item.name}: ${res.stderr}`);
    }
    const outPath = path.join(OUT_DIR, `${item.name}.json`);
    fs.writeFileSync(outPath, res.stdout, "utf8");
    manifestLines.push(
      `| \`${item.name}.json\` | \`node jest.js --runInBand --json --runTestsByPath ${item.extraArgs.join(" ")} ${relTestName}\` | \`${res.status}\` |`
    );
    fs.unlinkSync(testFile);
  }

  fs.writeFileSync(path.join(OUT_DIR, "README.md"), manifestLines.join("\n") + "\n", "utf8");
  fs.rmSync(workDir, { recursive: true, force: true });
  console.log(`Captured ${CASES.length} real Jest JSON files into ${OUT_DIR}`);
}

main();
